from __future__ import annotations

import re
import threading
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Literal

import mlflow
from fastapi import APIRouter, HTTPException
from pydantic import BaseModel, Field

from evals.run_offline_eval import run_offline_eval
from utils.agent_logger import get_agent_logger, new_id
from utils.config import PROJECT_ROOT
from utils.mlflow_utils import ensure_tracking_uri_configured


LOGGER = get_agent_logger(__name__)

router = APIRouter(prefix="/evals", tags=["evals"])

# dataset paths from client requests are only ever allowed to resolve inside here -- otherwise
# an absolute path or a `..`-laden relative one would let a caller point run_offline_eval() at
# any file readable by this process (e.g. `.env`), not just golden-dataset JSONL files.
_EVALS_DIR = (PROJECT_ROOT / "evals").resolve()

# eval_id is generated by new_id() (a 12-char lowercase hex string) and gets embedded verbatim
# into an MLflow search filter_string below -- this format check stands in for parameterization
# (the MLflow search DSL has no query-param API to bind against) so a crafted eval_id path
# segment can't break out of the string literal and inject extra filter clauses.
_EVAL_ID_RE = re.compile(r"^[0-9a-f]{12}$")

_RUN_TYPE_TAG_FILTER = "tags.run_type = 'offline_eval'"

_STATUS_BY_MLFLOW_STATUS: dict[str, Literal["running", "completed", "failed"]] = {
	"RUNNING": "running",
	"SCHEDULED": "running",
	"FINISHED": "completed",
	"FAILED": "failed",
	"KILLED": "failed",
}

_SUMMARY_METRIC_KEYS = (
	"total_cases",
	"evaluated_cases",
	"errored_cases",
	"true_positive",
	"false_positive",
	"false_negative",
	"true_negative",
	"accuracy",
	"precision",
	"recall",
	"f1",
	"score_in_range_rate",
	"mean_predicted_score",
)


class EvalTriggerRequest(BaseModel):
	dataset: str = Field(
		default="evals/golden_dataset.jsonl",
		description="Path to a golden-dataset JSONL file, relative to evals/ (must resolve inside "
		"it -- absolute paths and `..` are rejected).",
	)
	prompt_source: Literal["production", "local"] = Field(
		default="production",
		description="'production' read-only-loads the MLflow-registered prompt at the "
		"'production' alias. 'local' scores prompts/job_match_v1.txt as it sits on disk right "
		"now, without registering/promoting it -- use this to validate an edit before the next "
		"live cycle auto-promotes it.",
	)
	provider: str | None = Field(default=None, description="Overrides LLM_PROVIDER for this run. Currently 'gemini' is the only accepted value.")
	model: str | None = Field(default=None, description="Overrides the active provider's model env var for this run.")
	threshold: int | None = Field(default=None, description="Overrides MATCH_THRESHOLD (0-100) for this run.")
	experiment_name: str | None = Field(default=None, description="Overrides MLFLOW_EVAL_EXPERIMENT_NAME for this run.")
	run_name: str | None = Field(default=None, description="MLflow run name; defaults to this trigger's eval_id.")
	limit: int | None = Field(
		default=None,
		description="Only score the first N cases. Recommended when testing via this page -- "
		"omitting it scores the entire dataset (60 cases in golden_dataset.jsonl), which makes "
		"that many real, billed Gemini calls and can take 10+ minutes under the default RPM cap.",
	)

	model_config = {
		"json_schema_extra": {
			"examples": [
				{
					"dataset": "evals/golden_dataset.jsonl",
	 				"prompt_source": "local",
					"limit": "null"
				}
			]
		}
	}


class EvalTriggerResponse(BaseModel):
	eval_id: str
	status: Literal["running"]


class EvalStatusResponse(BaseModel):
	eval_id: str
	run_id: str
	status: Literal["running", "completed", "failed"]
	started_at: str | None
	finished_at: str | None
	experiment_name: str | None = None
	run_name: str | None = None
	dataset_path: str | None = None
	prompt_source: str | None = None
	prompt_version: str | None = None
	llm_provider: str | None = None
	llm_model: str | None = None
	match_threshold: float | None = None
	dataset_case_count: int | None = None
	limit: int | None = None
	result: dict[str, Any] | None = None
	error: str | None = None


def _resolve_dataset_path(raw: str) -> Path:
	candidate = Path(raw)
	if candidate.is_absolute():
		raise HTTPException(status_code=400, detail="dataset must be a relative path under evals/")
	resolved = (PROJECT_ROOT / candidate).resolve()
	if not resolved.is_relative_to(_EVALS_DIR):
		raise HTTPException(status_code=400, detail="dataset must resolve to a path under evals/")
	return resolved


def _run_eval_in_background(eval_id: str, dataset_path: Path, payload: EvalTriggerRequest, run_name: str) -> None:
	log = LOGGER.bind(eval_id=eval_id)
	log.action("api_eval_started", dataset=str(dataset_path))
	try:
		summary = run_offline_eval(
			eval_id=eval_id,
			dataset_path=dataset_path,
			prompt_source=payload.prompt_source,
			provider=payload.provider,
			model=payload.model,
			threshold=payload.threshold,
			experiment_name=payload.experiment_name,
			run_name=run_name,
			limit=payload.limit,
		)
	except Exception:
		# run_offline_eval() already tagged error_message on the MLflow run and marked it FAILED
		# before re-raising (see its docstring comment) -- this is just process-log visibility for
		# whoever is watching stdout, not a second bookkeeping path.
		log.exception("Eval run failed")
		return
	log.action("api_eval_completed", **summary)


def _ms_to_iso(ms: int | None) -> str | None:
	if not ms:
		return None
	return datetime.fromtimestamp(ms / 1000, tz=timezone.utc).isoformat()


def _coerce_metric(value: float) -> int | float:
	if isinstance(value, float) and value.is_integer():
		return int(value)
	return value


def _run_to_status_response(run: Any, experiment_name_by_id: dict[str, str]) -> EvalStatusResponse:
	tags = run.data.tags
	params = run.data.params
	metrics = run.data.metrics
	status = _STATUS_BY_MLFLOW_STATUS.get(run.info.status, "running")

	experiment_id = run.info.experiment_id
	experiment_name = experiment_name_by_id.get(experiment_id)
	if experiment_name is None:
		experiment = mlflow.get_experiment(experiment_id)
		experiment_name = experiment.name if experiment is not None else None
		experiment_name_by_id[experiment_id] = experiment_name

	result = None
	if status == "completed":
		result = {key: _coerce_metric(metrics[key]) for key in _SUMMARY_METRIC_KEYS if key in metrics}

	threshold = params.get("match_threshold")
	dataset_case_count = params.get("dataset_case_count")
	limit = params.get("limit")

	return EvalStatusResponse(
		eval_id=tags.get("eval_id", ""),
		run_id=run.info.run_id,
		status=status,
		started_at=_ms_to_iso(run.info.start_time),
		finished_at=_ms_to_iso(run.info.end_time),
		experiment_name=experiment_name,
		run_name=tags.get("mlflow.runName"),
		dataset_path=tags.get("dataset_path"),
		prompt_source=tags.get("prompt_source"),
		prompt_version=params.get("prompt_version"),
		llm_provider=tags.get("llm_provider") or params.get("llm_provider"),
		llm_model=params.get("llm_model"),
		match_threshold=float(threshold) if threshold is not None else None,
		dataset_case_count=int(dataset_case_count) if dataset_case_count is not None else None,
		limit=int(limit) if limit is not None else None,
		result=result,
		error=tags.get("error_message") if status == "failed" else None,
	)


@router.post("", status_code=202, summary="Trigger an offline eval run")
def trigger_eval(payload: EvalTriggerRequest) -> EvalTriggerResponse:
	"""Kicks off evals/run_offline_eval.py's run_offline_eval() on a background thread and
	returns immediately -- a full run against the real golden dataset can take 10+ minutes under
	the default RPM cap, far longer than is reasonable to hold an HTTP request open for. Poll
	GET /evals/{eval_id} for status/result. Concurrent triggers are not serialized against each
	other; they share the same Redis-backed RPM budget as everything else (rate_limiter.py), and
	each gets its own MLflow run via a distinct run_name, so running more than one at once is
	safe, just slower per-run.
	"""
	dataset_path = _resolve_dataset_path(payload.dataset)
	if not dataset_path.exists():
		raise HTTPException(status_code=400, detail=f"Dataset not found: {dataset_path}")

	eval_id = new_id()
	run_name = payload.run_name or eval_id

	thread = threading.Thread(
		target=_run_eval_in_background,
		args=(eval_id, dataset_path, payload, run_name),
		daemon=True,
		name=f"eval-{eval_id}",
	)
	thread.start()
	return EvalTriggerResponse(eval_id=eval_id, status="running")


@router.get("/{eval_id}", summary="Poll an eval run's status/result")
def get_eval(eval_id: str) -> EvalStatusResponse:
	"""Looks the run up in MLflow by its `eval_id` tag (durable across server restarts) rather
	than in-process memory -- run_offline_eval() tags every run it starts with the same eval_id
	this endpoint was handed at trigger time. `status` mirrors the MLflow run's own status until
	it reaches FINISHED/FAILED. On "completed", `result` holds the same summary fields the CLI
	prints (accuracy/precision/recall/f1/...), read back from the run's logged metrics. On
	"failed", `error` holds the error_message tag that run_offline_eval() attaches before
	re-raising -- check this first if a run seems stuck, since a bad dataset or an unreachable
	MLflow tracking server surfaces here rather than as an HTTP error (the trigger request already
	returned 202 by the time either of those would be discovered).

	Caveat: if this process is killed mid-run (not a graceful failure), MLflow has no way to know
	that and the run stays "running" forever until someone marks it FAILED by hand in the MLflow
	UI/API.
	"""
	if not _EVAL_ID_RE.match(eval_id):
		raise HTTPException(status_code=400, detail="eval_id is not a well-formed eval id")

	ensure_tracking_uri_configured()
	runs = mlflow.search_runs(
		search_all_experiments=True,
		filter_string=f"{_RUN_TYPE_TAG_FILTER} and tags.eval_id = '{eval_id}'",
		max_results=1,
		output_format="list",
	)
	if not runs:
		raise HTTPException(status_code=404, detail=f"No eval run with id {eval_id!r}")
	return _run_to_status_response(runs[0], {})


@router.get("", summary="List eval runs")
def list_evals(limit: int = 50) -> list[EvalStatusResponse]:
	"""Lists offline eval runs (tags.run_type = 'offline_eval') from MLflow, newest first --
	MLflow is the durable store, so this survives server restarts (unlike the old in-memory
	list, which reset on every deploy). `limit` caps how many runs come back (default 50)."""
	ensure_tracking_uri_configured()
	runs = mlflow.search_runs(
		search_all_experiments=True,
		filter_string=_RUN_TYPE_TAG_FILTER,
		max_results=limit,
		order_by=["attributes.start_time DESC"],
		output_format="list",
	)
	experiment_name_by_id: dict[str, str] = {}
	return [_run_to_status_response(run, experiment_name_by_id) for run in runs]
